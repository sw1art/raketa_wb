"""Repository interfaces and unit-of-work port.

The domain depends only on these abstractions; concrete implementations use
SQLAlchemy / PostgreSQL in the infrastructure layer.
"""
from __future__ import annotations

from typing import Protocol
from uuid import UUID

from ..entities import (
    HistoryEntry,
    Operation,
    OperationItem,
    Product,
    Reservation,
    ReservationView,
    Shipment,
    Stock,
    StockMovement,
    Store,
    Transfer,
    TransferView,
    Warehouse,
)
from ..enums import ShipmentStatus, ShipmentType
from ..events import DomainEvent


class StoreRepository(Protocol):
    async def get(self, store_id: UUID) -> Store | None: ...
    async def get_default(self) -> Store | None: ...
    async def create(self, store: Store) -> Store: ...


class ProductRepository(Protocol):
    async def get(self, product_id: UUID) -> Product | None: ...
    async def get_by_sku(self, store_id: UUID, sku: str) -> Product | None: ...
    async def create(self, product: Product) -> Product: ...
    async def update(self, product: Product) -> Product: ...
    async def list(
        self, *, sku: str | None, name: str | None, offset: int, limit: int
    ) -> tuple[list[Product], int]: ...


class WarehouseRepository(Protocol):
    async def get(self, warehouse_id: UUID) -> Warehouse | None: ...
    async def get_by_name(self, name: str) -> Warehouse | None: ...
    async def create(self, warehouse: Warehouse) -> Warehouse: ...
    async def update(self, warehouse: Warehouse) -> Warehouse: ...
    async def list(self, *, active_only: bool = False) -> list[Warehouse]: ...


class StockRepository(Protocol):
    async def get(self, product_id: UUID, warehouse_id: UUID) -> Stock | None: ...
    async def get_for_update(self, product_id: UUID, warehouse_id: UUID) -> Stock | None: ...
    async def get_or_create_for_update(self, product_id: UUID, warehouse_id: UUID) -> Stock: ...
    async def save(self, stock: Stock) -> None: ...
    async def nonzero_by_warehouse(self, warehouse_id: UUID) -> list[tuple[Stock, Product]]: ...
    async def available_by_product(
        self, product_id: UUID, exclude_warehouse_id: UUID | None
    ) -> list[tuple[Warehouse, int]]: ...
    async def list_joined(
        self, *, sku: str | None, name: str | None, warehouse_id: UUID | None
    ) -> list[tuple[Stock, Product, Warehouse]]: ...


class ReservationRepository(Protocol):
    async def get(self, reservation_id: UUID) -> Reservation | None: ...
    async def get_for_update(self, reservation_id: UUID) -> Reservation | None: ...
    async def create(self, reservation: Reservation) -> Reservation: ...
    async def save(self, reservation: Reservation) -> Reservation: ...
    async def count_active_by_warehouse(self, warehouse_id: UUID) -> int: ...
    async def list_joined(self, *, status: str | None) -> list[ReservationView]: ...


class TransferRepository(Protocol):
    async def get(self, transfer_id: UUID) -> Transfer | None: ...
    async def get_for_update(self, transfer_id: UUID) -> Transfer | None: ...
    async def create(self, transfer: Transfer) -> Transfer: ...
    async def save(self, transfer: Transfer) -> Transfer: ...
    async def count_open_by_warehouse(self, warehouse_id: UUID) -> int: ...
    async def list_in_transit(self) -> list[Transfer]: ...
    async def list_joined(self, *, status: str | None) -> list[TransferView]: ...


class ShipmentRepository(Protocol):
    async def get(self, shipment_id: UUID) -> Shipment | None: ...
    async def get_for_update(self, shipment_id: UUID) -> Shipment | None: ...
    async def get_by_reservation(self, reservation_id: UUID) -> Shipment | None: ...
    async def create(self, shipment: Shipment) -> Shipment: ...
    async def save(self, shipment: Shipment) -> Shipment: ...
    async def count_open_by_warehouse(self, warehouse_id: UUID) -> int: ...
    async def list_in_transit(self) -> list[Shipment]: ...
    async def list(
        self,
        *,
        shipment_type: ShipmentType | None,
        status: ShipmentStatus | None,
        offset: int,
        limit: int,
    ) -> tuple[list[Shipment], int]: ...


class OperationRepository(Protocol):
    async def create(
        self,
        operation: Operation,
        items: list[OperationItem],
        movements: list[StockMovement],
    ) -> Operation: ...
    async def get(self, operation_id: UUID) -> Operation | None: ...
    async def get_by_idempotency_key(self, key: str) -> Operation | None: ...
    async def list_history(
        self,
        *,
        operation_type: str | None,
        sku: str | None,
        offset: int,
        limit: int,
    ) -> tuple[list[HistoryEntry], int]: ...
    async def get_history(self, operation_id: UUID) -> list[HistoryEntry]: ...


class OutboxRepository(Protocol):
    async def add(self, event: DomainEvent) -> None: ...


class UnitOfWork(Protocol):
    stores: StoreRepository
    products: ProductRepository
    warehouses: WarehouseRepository
    stocks: StockRepository
    reservations: ReservationRepository
    transfers: TransferRepository
    shipments: ShipmentRepository
    operations: OperationRepository
    outbox: OutboxRepository

    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...
    async def close(self) -> None: ...
